"""Synchronise with an existing FreeCAD document.

The model on disk is the user's, not ours. Someone may have opened it in FreeCAD and edited
it by hand, so sync has to answer three questions honestly:

1. Which objects are ours, and what does the model actually measure now?
2. Which objects did we put there for boolean scaffolding (and must therefore ignore)?
3. Which objects are neither — i.e. added outside ArchPilot — and should be surfaced to the
   user rather than silently measured or silently deleted?

Object 3 is reported, never merged into quantities and never removed.
"""
from __future__ import annotations

import time
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from archpilot.cad.client import SYNC_OK_PREFIX, FreeCADInstall, RunResult, run_script
from archpilot.cad.manifest import (
    MeasuredObject,
    ObjectRecord,
    read_sync_document,
    results_only,
    total_volume_m3,
)
from archpilot.cad.scripts import fill_template, literal
from archpilot.core.errors import FreeCADOperationFailed, FreeCADTimeout
from archpilot.spec.schema import BuildingSpec

SYNC_TEMPLATE = r'''# Generated by ArchPilot — reads an existing document. Does not modify it.
import json
import os
import sys
import traceback

import FreeCAD

# Paths are injected as escaped Python literals, so a path containing a quote or a backslash
# cannot break the generated script.
IN_FCSTD = __IN_FCSTD__
OUT_SYNC = __OUT_SYNC__


def fail(message):
    # flush is essential: freecadcmd discards buffered stdout when a script exits via
    # sys.exit, which would otherwise leave the user staring at an empty error message.
    print("ARCHPILOT_ERROR %s" % message, flush=True)
    sys.exit(1)


def measure(obj):
    shape = obj.Shape
    bb = shape.BoundBox
    return {
        "ap_id": getattr(obj, "AP_ID", ""),
        "ap_kind": getattr(obj, "AP_KIND", ""),
        "storey": getattr(obj, "AP_STOREY", ""),
        "label": obj.Label,
        "role": getattr(obj, "AP_ROLE", ""),
        "volume_m3": shape.Volume / 1e9,
        "surface_area_m2": shape.Area / 1e6,
        "bbox_m": [bb.XLength / 1000.0, bb.YLength / 1000.0, bb.ZLength / 1000.0],
        "bbox_min_m": [bb.XMin / 1000.0, bb.YMin / 1000.0, bb.ZMin / 1000.0],
        "solids": len(shape.Solids),
        "valid": bool(shape.isValid()),
        "meta": {k[3:].lower(): getattr(obj, k) for k in
                 ("AP_PLAN_AREA_M2", "AP_THICKNESS_M", "AP_SLAB_KIND",
                  "AP_LENGTH_M", "AP_HEIGHT_M", "AP_OPENING_COUNT",
                  "AP_OPENING_AREA_M2") if hasattr(obj, k)},
    }


def main():
    if not os.path.isfile(IN_FCSTD):
        fail("the model file no longer exists: %s" % IN_FCSTD)

    doc = FreeCAD.openDocument(IN_FCSTD)
    results = []
    external = []

    for obj in doc.Objects:
        role = getattr(obj, "AP_ROLE", "")
        if not role:
            try:
                volume = obj.Shape.Volume / 1e9
            except Exception:
                continue        # no shape (sketch, datum, folder) — not a solid to report
            external.append({
                "name": obj.Name,
                "label": obj.Label,
                "type_id": str(obj.TypeId),
                "volume_m3": volume,
                "visible": bool(getattr(obj, "Visibility", True)),
            })
            continue
        if role != "result":
            continue
        if getattr(obj, "AP_ID", ""):
            results.append(measure(obj))

    with open(OUT_SYNC, "w", encoding="utf-8") as fh:
        json.dump({"results": results, "external": external}, fh, indent=1)

    print("ARCHPILOT_SYNC_OK %d" % len(results), flush=True)


try:
    main()
except SystemExit:
    raise
except Exception:
    traceback.print_exc()
    sys.stderr.flush()
    print("ARCHPILOT_ERROR unhandled exception during sync", flush=True)
    sys.exit(1)
'''


@dataclass
class SyncResult:
    fcstd_path: Path
    manifest: list[MeasuredObject]
    external: list[ObjectRecord] = field(default_factory=list)
    log: str = ""
    duration_s: float = 0.0

    @property
    def results(self) -> list[MeasuredObject]:
        return results_only(self.manifest)

    @property
    def total_volume_m3(self) -> float:
        return total_volume_m3(self.manifest)

    def by_id(self, ap_id: str) -> MeasuredObject | None:
        return next((m for m in self.manifest if m.ap_id == ap_id), None)

    @property
    def invalid_objects(self) -> list[MeasuredObject]:
        return [m for m in self.manifest if not m.valid]


def render_sync(fcstd_path: str, out_sync: str) -> str:
    return fill_template(SYNC_TEMPLATE, {
        "__IN_FCSTD__": literal(fcstd_path),
        "__OUT_SYNC__": literal(out_sync),
    })


def sync_model(install: FreeCADInstall, fcstd_path: Path, workdir: Path,
               timeout_s: int = 180, runner: Callable[..., RunResult] = run_script,
               ) -> SyncResult:
    """Read an existing model and report what it now contains.

    Raises rather than returning a partial picture if FreeCAD fails.
    """
    fcstd_path = Path(fcstd_path).resolve()
    if not fcstd_path.is_file():
        raise FreeCADOperationFailed("That model file does not exist.",
                                     detail=str(fcstd_path))
    workdir = Path(workdir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    sync_path = workdir / "sync_report.json"
    script_path = workdir / "sync_model.py"
    script_path.write_text(render_sync(str(fcstd_path), str(sync_path)), encoding="utf-8")

    started = time.perf_counter()
    result = runner(install.executable, script_path, timeout_s=timeout_s)
    duration = time.perf_counter() - started

    if result.timed_out:
        raise FreeCADTimeout(
            f"FreeCAD did not finish reading the model within {timeout_s} s.")
    if not result.has_sentinel(SYNC_OK_PREFIX):
        raise FreeCADOperationFailed("FreeCAD could not read the model.",
                                     detail=result.summary())

    manifest, external = read_sync_document(sync_path)
    log = (result.stdout + "\n" + result.stderr).strip()
    return SyncResult(fcstd_path=fcstd_path, manifest=manifest, external=external,
                      log=log, duration_s=duration)


def compare(spec: BuildingSpec, sync: SyncResult, rel_tol: float = 0.02) -> list[str]:
    """Describe how the model on disk differs from the design — read-only, never repairs."""
    notes: list[str] = []

    designed: dict[str, tuple[str, float]] = {}
    for st in spec.storeys:
        for slab in st.slabs:
            designed[slab.id] = ("slab", slab.volume_m3)
        for wall in st.walls:
            designed[wall.id] = ("wall", wall.net_volume_m3)

    present = {m.ap_id: m for m in sync.results}

    for missing in sorted(set(designed) - set(present)):
        notes.append(f"Design element '{missing}' is not in the model — it will be rebuilt.")

    for extra in sorted(set(present) - set(designed)):
        notes.append(f"The model contains '{extra}', which is no longer in the design.")

    for ap_id, (kind, expected) in designed.items():
        found = present.get(ap_id)
        if found is None or expected <= 1e-9:
            continue
        if abs(found.volume_m3 - expected) / expected > rel_tol:
            notes.append(
                f"'{ap_id}' ({kind}) measures {found.volume_m3:.3f} m³ in the model but "
                f"{expected:.3f} m³ in the design — it has been edited or rebuilt.")

    for record in sync.external:
        notes.append(
            f"'{record.describe()}' was added to the model outside ArchPilot. It is left "
            f"untouched and is not included in quantities.")
    return notes


def external_object_summary(sync: SyncResult) -> str:
    if not sync.external:
        return "No objects were added outside ArchPilot."
    return (f"{len(sync.external)} object(s) in the model were not created by ArchPilot: "
            + ", ".join(r.describe() for r in sync.external))
